class Task:
    """Discovery data of one (model, task): exact patches (pair x unit) and RelP per pair at both endpoints."""

    def __init__(self, model, task):
        import torch
        self.model, self.task = model, task
        self.d = D.task_dir(model, task)
        self.rows = [json.loads(l) for l in (ROOT / f"data/relp_sva/{model}_paper_v1/{task}/discovery.jsonl").read_text().splitlines()]
        self.n = len(self.rows)
        self.T = len(self.rows[0]["input_ids"])
        self.subj = min(min(r["changed_positions"]) for r in self.rows)
        pr = torch.load(self.d / "score_endpointB/per_row_expert_scores.pt", map_location="cpu", weights_only=True)
        self.rA, self.rB = pr["A"].numpy(), pr["B"].numpy()          # [n, L, T, E]
        assert pr["row_ids"] == [r["row_id"] for r in self.rows]
        self.L, self.E = self.rA.shape[1], self.rA.shape[3]
        cols = ["row", "direction", "kind", "layer", "pos", "expert", "active_A", "active_B", "effect", "route_changes"]
        import pyarrow.dataset as ds
        import glob
        f = ds.field("split") == "discovery"
        p = ds.dataset(sorted(glob.glob(str(self.d / "patch_full/part_*.parquet")))).to_table(columns=cols, filter=f).to_pandas()
        self.pos_units = p[p.kind == "position"].drop(columns=["expert", "active_A", "active_B", "kind"])
        e = p[p.kind == "expert"].drop(columns=["kind"])
        e["cls"] = np.where(e.active_A & e.active_B, "both", np.where(e.active_A, "clean_only", "corrupt_only"))
        e["relp_B"] = self.rB[e.row.values, e.layer.values, e.pos.values, e.expert.values]
        e["relp_A"] = self.rA[e.row.values, e.layer.values, e.pos.values, e.expert.values]
        self.exp = e
        pu = self.pos_units
        pu["relp_B"] = self.rB.sum(-1)[pu.row.values, pu.layer.values, pu.pos.values]
        pu["relp_A"] = self.rA.sum(-1)[pu.row.values, pu.layer.values, pu.pos.values]
        self.group = np.array([r["group_id"] for r in self.rows])
        self.case = np.array([r["case"] for r in self.rows])

    def pos_class(self, pos):
        pos = np.asarray(pos)
        return np.where((pos == self.subj) & (pos == self.T - 1), "subject=final",
                        np.where(pos == self.subj, "subject", np.where(pos == self.T - 1, "final", "between")))

    def unit_table(self) -> pd.DataFrame:
        """S1.0: one row per expert-position unit (discovery means; absent = 0)."""
        n = self.n
        out = []
        for direction, rel in (("denoise", "relp_B"), ("noise", "relp_A")):
            e = self.exp[self.exp.direction == direction]
            e = e.assign(e2=e.effect.astype(float) ** 2, r2=e[rel].astype(float) ** 2)
            g = e.groupby(["layer", "pos", "expert"])
            s = g.effect.sum()
            s2 = g.e2.sum()
            m = s / n
            se = np.sqrt(((s2 / n - m ** 2).clip(lower=0) * n / (n - 1)) / n)
            r = g[rel].sum() / n
            rs2 = g.r2.sum()
            rse = np.sqrt(((rs2 / n - r ** 2).clip(lower=0) * n / (n - 1)) / n)
            df = pd.DataFrame({f"exact_{direction}": m, f"exact_{direction}_se": se, f"{rel}": r, f"{rel}_se": rse})
            if direction == "denoise":
                cnt = g.size()
                df["n_present"] = cnt
                for c in CLASSES:
                    df[f"share_{c}"] = e[e.cls == c].groupby(["layer", "pos", "expert"]).size().reindex(df.index).fillna(0) / n
                df["route_changes"] = g.route_changes.mean()
            out.append(df)
        u = out[0].join(out[1], how="outer").fillna(0.0).reset_index()
        u["pos_class"] = self.pos_class(u.pos.values)
        u["band"] = D.band_of(u.layer.values, self.L)
        for col in ("exact_denoise", "relp_B", "exact_noise", "relp_A"):
            u[f"rank_{col}"] = u[col].abs().rank(ascending=False, method="first").astype(int)
        u["sig_exact"] = u.exact_denoise.abs() > 2 * u.exact_denoise_se
        u["sig_relp"] = u.relp_B.abs() > 2 * u.relp_B_se
        return u


