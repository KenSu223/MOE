def pearson(x, y):
    x, y = np.asarray(x, float), np.asarray(y, float)
    if len(x) < 3 or x.std() == 0 or y.std() == 0:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def spearman(x, y):
    return pearson(pd.Series(x).rank().values, pd.Series(y).rank().values)


def slope0(x, y):
    """Least-squares slope of y on x through the origin (exact on RelP)."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    return float((x * y).sum() / (x * x).sum()) if (x * x).sum() > 0 else float("nan")


def fmt(x, nd=2):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "-"
    return f"{x:.{nd}f}" if isinstance(x, (float, np.floating)) else str(x)


def md_table(df, nd=2):
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(fmt(r[c], nd) if isinstance(r[c], (float, np.floating)) else str(r[c]) for c in cols) + " |")
    return "\n".join(lines) + "\n"


def write_table(name, title, blocks):
    text = f"# {title}\n\nGenerated by scripts/relp_moe_p8_analyze.py (Phase 8; docs/relp_moe_phase8_plan.md).\n\n"
    for head, df, nd, note in blocks:
        text += f"## {head}\n\n" + (note + "\n\n" if note else "") + md_table(df, nd) + "\n"
    (TAB / f"relp_moe_p8_{name}.md").write_text(text)


