def _complete(p):
    f = Path(p) / "run_meta.json"
    return f.exists() and json.loads(f.read_text()).get("status") == "complete"


def _means(sc: pd.DataFrame, cols, n):
    return sc.groupby(["layer", "pos", "expert"])[cols].sum() / n


def _variant_metrics(j, col, exact="exact_denoise"):
    sig = j[(j.sig_exact) | (j.sig_relp)]
    out = {"pearson": pearson(j[col], j[exact]), "spearman_nonzero": spearman(sig[col], sig[exact]),
           "slope_exact_on_score": slope0(j[col], j[exact])}
    rx = set(map(tuple, j.reindex(j[exact].abs().sort_values(ascending=False).index).head(20)[["layer", "pos", "expert"]].values))
    rv = set(map(tuple, j.reindex(j[col].abs().sort_values(ascending=False).index).head(20)[["layer", "pos", "expert"]].values))
    out["top20_overlap_exact"] = len(rx & rv) / 20
    for band in ("L0", "L1-2", "last8"):
        b = j[j.band == band]
        out[f"pearson_{band}"] = pearson(b[col], b[exact])
        out[f"slope_{band}"] = slope0(b[col], b[exact])
    return out


