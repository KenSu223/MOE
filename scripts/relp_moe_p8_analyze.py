def s23(models, summary):
    """S2.3: which frozen quantity causes the gap between exact patching and RelP."""
    recs, named, d3 = [], [], []
    for model in models:
        for task in D.TASKS:
            d = D.task_dir(model, task)
            if not (_complete(d / "p8_freeze") and _complete(d / "p8_rules")):
                continue
            fz = pd.read_parquet(d / "p8_freeze/freeze.parquet")
            spec = D.load_json(d / "p8_freeze/units.json")
            n = int(fz.row.nunique())
            sc = D.load_sparse(d / "p8_rules/scores_B.npz")
            sc = sc[sc.row < n]
            effs = [c for c in fz.columns if c.startswith("effect_")]
            g = fz.groupby("unit")[effs].sum() / n
            # RelP / RelP without the half rule for the same units (position unit = sum over its experts)
            ru = sc.groupby(["layer", "pos", "expert"])[["relp", "relp_nohalf", "grad"]].sum() / n
            rp = sc.groupby(["layer", "pos"])[["relp", "relp_nohalf", "grad"]].sum() / n
            rows = []
            for ui, s_ in enumerate(spec):
                if ui not in g.index:
                    continue
                key = (s_["layer"], s_["pos"]) if s_["kind"] == "position" else (s_["layer"], s_["pos"], s_["expert"])
                src = rp if s_["kind"] == "position" else ru
                r = src.loc[key] if key in src.index else pd.Series({"relp": 0.0, "relp_nohalf": 0.0, "grad": 0.0})
                rows.append({"unit": ui, "kind": s_["kind"], "layer": s_["layer"], "pos": s_["pos"], "expert": s_["expert"],
                             "sources": "+".join(s_["sources"]), **g.loc[ui].to_dict(), "relp": float(r["relp"]),
                             "relp_nohalf": float(r["relp_nohalf"]), "grad": float(r["grad"])})
            U = pd.DataFrame(rows)
            L = int(U.layer.max()) + 1
            rws = [json.loads(l) for l in (ROOT / f"data/relp_sva/{model}_paper_v1/{task}/discovery.jsonl").read_text().splitlines()]
            subj, T = min(min(r["changed_positions"]) for r in rws), len(rws[0]["input_ids"])
            U["band"] = D.band_of(U.layer.values, L)
            U["pos_class"] = np.where((U.pos == subj) & (U.pos == T - 1), "subject=final", np.where(U.pos == subj, "subject",
                                      np.where(U.pos == T - 1, "final", "between")))
            nat = U.effect_natural
            U["gap"] = nat - U.relp
            U["t_set"] = nat - U.effect_Rset
            U["t_weights"] = U.effect_Rset - U.effect_R
            U["t_routing"] = nat - U.effect_R
            U["t_attention"] = U.effect_R - U.effect_RA
            U["t_norm"] = U.effect_RA - U.effect_RAN
            U["t_normnl"] = U.effect_RA - U.relp_nohalf           # later norms + expert-activation nonlinearity + higher order
            U["ran_diverged"] = ~np.isfinite(U.effect_RAN) | (U.effect_RAN.abs() > 10 * np.maximum(U.effect_natural.abs(), 1.0))
            U["t_nonlin"] = np.where(U.ran_diverged, np.nan, U.effect_RAN - U.relp_nohalf)
            U.loc[U.ran_diverged, "t_norm"] = np.nan
            U["t_gate"] = U.effect_RAN - U.effect_RANG             # diagnostic only (ill-conditioned split, see report)
            U["t_finite"] = U.effect_RANG - U.relp_nohalf
            U["t_half"] = U.relp_nohalf - U.relp
            U["solo_attention"] = nat - U.effect_A
            U["solo_norm"] = nat - U.effect_N
            U["diverged"] = ~np.isfinite(U.effect_RANG) | (U.effect_RANG.abs() > 10 * np.maximum(nat.abs(), 1.0))
            U["model"], U["task"] = model, task
            recs.append(U)
            # D3: natural variant vs Phase 7 patch_full for the same pairs and units
            pf = D.patch_rows(d, "discovery", "denoise", None, ["row", "kind", "layer", "pos", "expert", "effect"])
            pf = pf[pf.row < n]
            m_ = fz.merge(pf, on=["row", "kind", "layer", "pos", "expert"])
            um = m_.groupby("unit")[["effect_natural", "effect"]].sum() / n
            d3.append({"model": model, "task": task, "pair_units": len(m_), "pearson_pairunits": pearson(m_.effect_natural, m_.effect),
                       "pearson_unit_means": pearson(um.effect_natural, um.effect),
                       "max_abs_unit_mean_diff": float((um.effect_natural - um.effect).abs().max())})
    if not recs:
        return
    U = pd.concat(recs)
    U.to_parquet(OUT / "s23_freeze_units.parquet", index=False)
    terms = ["t_set", "t_weights", "t_attention", "t_normnl", "t_half"]
    ok = U
    grp = ok.groupby(["model", "kind", "band", "pos_class"])
    dec = grp[["effect_natural", "relp", "gap"] + terms].sum()
    dec["units"] = grp.size()
    dec["ran_diverged"] = U[U.ran_diverged].groupby(["model", "kind", "band", "pos_class"]).size().reindex(dec.index).fillna(0).astype(int)
    split_ok = U[~U.ran_diverged].groupby(["model", "kind", "band", "pos_class"])[["t_norm", "t_nonlin"]].sum()
    dec = dec.join(split_ok.add_suffix("_where_defined"))
    dec["rang_diverged"] = U[U.diverged].groupby(["model", "kind", "band", "pos_class"]).size().reindex(dec.index).fillna(0).astype(int)
    for t_ in terms:
        dec[f"share_{t_[2:]}"] = dec[t_] / dec["gap"].where(dec["gap"].abs() > 1e-3)
    dec = dec.reset_index()
    med = U.groupby(["model", "kind", "band", "pos_class"])[["gap"] + terms + ["t_norm", "t_nonlin", "solo_attention", "solo_norm"]].median().reset_index()
    div = U.groupby(["model", "kind", "band"]).agg(units=("diverged", "size"), RAN_diverged=("ran_diverged", "sum"), RANG_diverged=("diverged", "sum")).reset_index()
    picks = {"qwen3": [("position", 0, None), ("expert", 41, 36), ("expert", 46, 30), ("expert", 47, 111)],
             "mixtral": [("position", 0, None), ("expert", 0, 2), ("expert", 30, 2), ("expert", 31, 0)]}
    nm = []
    for model, lst in picks.items():
        for kind, l, e in lst:
            s = U[(U.model == model) & (U.kind == kind) & (U.layer == l) & ((U.expert == e) if e is not None else True)]
            s = s[(s.pos_class.str.startswith("subject")) if l == 0 else (s.pos_class.isin(["final", "subject=final"]))]
            for r in s.itertuples(index=False):
                nm.append({"model": model, "task": r.task, "unit": f"L{l}" + (f"E{e:03d}" if e is not None else " MoE output") + f" @ {r.pos_class}",
                           "exact": r.effect_natural, "relp": r.relp, "gap": r.gap, "set": r.t_set, "weights": r.t_weights,
                           "attention": r.t_attention, "norm+nonlin": r.t_normnl, "norm": r.t_norm, "nonlin": r.t_nonlin, "half": r.t_half,
                           "RANG_effect": r.effect_RANG, "RANG_diverged": bool(r.diverged)})
    NM, D3 = pd.DataFrame(nm), pd.DataFrame(d3)
    summary["s23"] = {"decomposition": dec.to_dict(orient="records"), "named": NM.to_dict(orient="records"), "D3": D3.to_dict(orient="records"),
                      "divergence": div.to_dict(orient="records")}
    write_table("freeze", "S2.3 Which frozen quantity causes RelP's error (denoise, first 100 discovery pairs, unit means)", [
        ("D3: natural variant vs Phase 7 patch_full (same pairs and units, other batch)", D3, 3, None),
        ("Named units", NM, 3, "gap = exact - RelP = set + weights + attention + norm+nonlin + half (exact telescoping sum). set / weights = later top-k set switches / later routing weights; attention = later attention patterns; norm+nonlin = exact effect with later routing and attention frozen minus its first-order term with the full product rule (relp_nohalf), i.e. later RMSNorm denominators + the experts' activation nonlinearity + higher-order terms, split into norm and nonlin where the norm-frozen patch stays bounded (nan where it diverges); half = relp_nohalf - relp. RANG_effect = the patch with the SiLU gates frozen as well (diagnostic: linearising the gates makes large perturbations blow up)."),
        ("Decomposition by unit kind, layer band and position class (sums over units)", dec, 3,
         "share_* = term / gap for the group (signed; terms can cancel)."),
        ("Medians per unit (all units)", med, 3, None),
        ("Units for which a frozen-norm patch diverges (|effect| > 10 x max(|exact|, 1)): RAN = routing + attention + norm frozen; RANG = + SiLU gates", div, 0, None)])


def s27(models, summary):
    """S2.7: single-neuron exact patches vs RelP per neuron."""
    recs, bins, expsum, offsets = [], [], [], []
    for model in models:
        for task in D.TASKS:
            d = D.task_dir(model, task)
            if not _complete(d / "p8_neuron"):
                continue
            nr = pd.read_parquet(d / "p8_neuron/neuron_patch.parquet")
            z = np.load(d / "p8_neuron/relp_neuron_rows.npz")
            info = D.load_json(d / "p8_neuron/neurons.json")
            n = z["v_relp"].shape[0]
            M = len(info)
            # per-pair offset of the patched rows (other GEMM shapes than the base row): median effect of the matched random
            # neurons of that pair, whose true effects are ~0; corrected effects subtract it
            nr = nr.assign(effect_raw=nr.effect, effect=nr.effect - D.patch_offsets(nr, info))
            o_ = nr.effect_raw - nr.effect
            offsets.append({"model": model, "task": task, "offset_median": float(o_.median()), "offset_mean": float(o_.mean()),
                            "offset_sd": float(o_.std()), "offset_p99_abs": float(o_.abs().quantile(0.99))})
            exr = np.zeros(M)
            np.add.at(exr, nr.neuron.values, nr.effect_raw.values)
            exr /= n
            ex = np.zeros(M)
            np.add.at(ex, nr.neuron.values, nr.effect.values)
            ex /= n
            ex2 = np.zeros(M)
            np.add.at(ex2, nr.neuron.values, nr.effect.values.astype(float) ** 2)
            se = np.sqrt(np.clip(ex2 / n - ex ** 2, 0, None) / n)
            df = pd.DataFrame({"neuron": np.arange(M), "exact": ex, "exact_raw": exr, "se": se,
                               **{k[2:]: z[k].mean(0) for k in z.files if k.startswith("v_")},
                               "sets": ["+".join(x["sets"]) for x in info],
                               "layer": [x["coordinate"][0] for x in info], "pos": [x["coordinate"][1] for x in info],
                               "expert": [x["coordinate"][2] for x in info]})
            top = df[df.sets.str.contains("top") & ~df.sets.str.fullmatch("top_expert")].copy()
            top["rank"] = top.relp.abs().rank(ascending=False, method="first")
            rnd = df[df.sets.str.contains("random")]
            floor = float(np.percentile(np.abs(rnd.exact), 95)) if len(rnd) else float("nan")
            for name, s in (("top 1000", top), ("random 1000", rnd), ("top expert-position", df[df.sets.str.contains("top_expert")])):
                recs.append({"model": model, "task": task, "set": name, "neurons": len(s), "pearson": pearson(s.relp, s.exact),
                             "pearson_nohalf": pearson(s.relp_nohalf, s.exact), "pearson_grad_rw": pearson(s.grad_rw, s.exact),
                             "slope": slope0(s.relp, s.exact), "slope_nohalf": slope0(s.relp_nohalf, s.exact),
                             "slope_grad_rw": slope0(s.grad_rw, s.exact),
                             "sign_agree": float((np.sign(s.relp) == np.sign(s.exact)).mean()),
                             "frac_above_random_p95": float((s.exact.abs() > floor).mean()), "random_p95_abs_exact": floor,
                             "mean_abs_exact": float(s.exact.abs().mean())})
            for lo, hi in ((1, 10), (11, 100), (101, 300), (301, 1000)):
                b = top[(top["rank"] >= lo) & (top["rank"] <= hi)]
                bins.append({"model": model, "task": task, "relp_rank": f"{lo}-{hi}", "neurons": len(b), "pearson": pearson(b.relp, b.exact),
                             "slope": slope0(b.relp, b.exact), "sign_agree": float((np.sign(b.relp) == np.sign(b.exact)).mean()),
                             "frac_above_random_p95": float((b.exact.abs() > floor).mean()), "median_abs_exact": float(b.exact.abs().median())})
            te = df[df.sets.str.contains("top_expert")]
            if len(te):
                l, t, e = int(te.layer.iloc[0]), int(te.pos.iloc[0]), int(te.expert.iloc[0])
                pf = D.exact_means(d)
                row = pf[(pf.layer == l) & (pf.pos == t) & (pf.expert == e)]
                expsum.append({"model": model, "task": task, "expert_position": f"L{l} pos{t} E{e:03d}", "neurons": len(te),
                               "sum_single_raw": float(te.exact_raw.sum()), "sum_single_corrected": float(te.exact.sum()),
                               "sum_single_neuron_relp": float(te.relp.sum()),
                               "expert_exact": float(row["mean"].iloc[0]) if len(row) else float("nan")})
    if not recs:
        return
    R, B, E, O = pd.DataFrame(recs), pd.DataFrame(bins), pd.DataFrame(expsum), pd.DataFrame(offsets)
    summary["s27"] = {"sets": R.to_dict(orient="records"), "bins": B.to_dict(orient="records"), "expert_sum": E.to_dict(orient="records"),
                      "offsets": O.to_dict(orient="records")}
    write_table("neuron", "S2.7 Single-neuron exact patches vs RelP (denoise, discovery, neuron means over 300 pairs)", [
        ("By neuron set", R, 3, "Exact effects corrected for the per-(pair, layer) offset (last table). *_nohalf = RelP without the half rule; *_grad_rw = the true gradient (incl. routing weights). slope = exact on score through the origin. random_p95_abs_exact = 95th percentile of |exact| over the matched random neurons (noise floor proxy)."),
        ("RelP's top 1,000 by rank", B, 3, None),
        ("Sum of single-neuron effects in the top expert-position vs the whole expert patch", E, 3,
         "raw = as measured; corrected = after subtracting each (pair, layer) offset (below)."),
        ("Offset of single-neuron patches per (pair, layer): median effect of the pair's random and top-expert neurons in that layer (>= 10 units; else the pair's random median)", O, 4,
         "Patched rows run later layers in other GEMM shapes than the unpatched row; bf16 rounding, amplified by downstream routing, gives every patch of a pair a common shift. It is negligible for single strong units and dominates sums over hundreds of weak ones.")])


def s21(models, summary):
    """S2.1: add-back curves (faithfulness / completeness) under each ranking; D2; additivity."""
    recs, d2, add = [], [], []
    for model in models:
        for task in D.TASKS:
            d = D.task_dir(model, task)
            if not _complete(d / "p8_addback"):
                continue
            s = pd.DataFrame(D.load_json(d / "p8_addback/summary.json"))
            s["model"], s["task"] = model, task
            recs.append(s)
            for split in ("validation", "test"):
                p7 = d / split / f"{split}_expert_position_mean_q_routed/summary.json"
                if not p7.exists():
                    continue
                a = pd.DataFrame(D.load_json(p7))
                a = a[a.ranking == "relp"]
                b = s[(s.ranking == "relp") & (s.unit == "expert_position") & (s.split == split)]
                m_ = a.merge(b, on=["budget", "intervention"], suffixes=("_p7", "_p8"))
                for r in m_.itertuples(index=False):
                    d2.append({"model": model, "task": task, "split": split, "budget": r.budget, "intervention": r.intervention,
                               "phase7": r.normalized_p7, "phase8": r.normalized_p8, "diff": r.normalized_p8 - r.normalized_p7})
            # additivity on held-out pairs: sum of single exact effects of the exact ranking's top-K vs the joint patch
            iv = pd.read_parquet(d / "p8_addback/interventions.parquet")
            rk = D.load_json(d / "p8_addback/rankings.json")["expert_position"]["exact"]
            ho = []
            for sp in ("validation", "test"):
                ho.append(D.patch_rows(d, sp, "denoise", "expert", ["row_id", "layer", "pos", "expert", "effect"]))
            ho = pd.concat(ho)
            rows_ = [json.loads(l) for l in (ROOT / f"data/relp_sva/{model}_paper_v1/{task}/discovery.jsonl").read_text().splitlines()]
            T, E = len(rows_[0]["input_ids"]), int(ho.expert.max()) + 1
            ho["flat"] = ho.layer * T * E + ho.pos * E + ho.expert
            nrow = iv.row_id.nunique()
            den = (iv.groupby("row_id").margin_A.first() - iv.groupby("row_id").margin_B.first()).mean()
            for K in (1, 2, 5, 10, 20, 50):
                single = ho[ho.flat.isin(rk[:K])].effect.sum() / nrow
                j = iv[(iv.ranking == "exact") & (iv.budget == K) & (iv.intervention == "denoise") & (iv.unit == "expert_position")]
                joint = (j.margin - j.margin_B).mean() if len(j) else float("nan")
                add.append({"model": model, "task": task, "K": K, "sum_single_exact": float(single / den), "joint_exact": float(joint / den)})
    if not recs:
        return
    S_ = pd.concat(recs)
    S_.to_parquet(OUT / "s21_addback.parquet", index=False)
    D2, A_ = pd.DataFrame(d2), pd.DataFrame(add)
    S_["value"] = np.where(S_.intervention == "noise", 1 - S_.normalized, S_.normalized)   # completeness = remaining share
    mean_t = S_[S_.split == "all"].groupby(["model", "unit", "intervention", "ranking", "budget"]).value.mean().reset_index()
    summary["s21"] = {"curves_mean_over_tasks": mean_t.to_dict(orient="records"), "D2": D2.to_dict(orient="records"),
                      "additivity": A_.to_dict(orient="records")}
    blocks = []
    for unit in ("expert_position", "expert_all_positions"):
        for iv_, lab in (("denoise", "faithfulness: share of the paired difference restored when only these units carry the clean run"),
                         ("noise", "completeness: share left when these units carry the corrupted run (ideal 0)"),
                         ("keep", "keep with the mean_q_routed baseline (the RelP paper's faithfulness)"),
                         ("remove", "remove with the mean_q_routed baseline (the RelP paper's completeness)")):
            x = mean_t[(mean_t.unit == unit) & (mean_t.intervention == iv_) & ~mean_t.ranking.str.startswith("path_")]
            x = x.assign(ranking=np.where(x.ranking == "random", "random (3 seeds)", x.ranking),
                         budget=np.where(x.ranking == "all", "all", x.budget.astype(str)))
            x = x.groupby(["model", "ranking", "budget"]).value.mean().reset_index()
            pv = x.pivot_table(index=["model", "ranking"], columns="budget", values="value")
            order = sorted([c for c in pv.columns if c != "all"], key=int) + (["all"] if "all" in pv.columns else [])
            blocks.append((f"{unit}: {lab} (validation + test, mean of 4 tasks)", pv[order].reset_index(), 2,
                           "all = every eligible unit of the pool (the ceiling); path_* rankings exist for two tasks only and are in the last table."))
    two = S_[(S_.split == "all") & S_.task.isin(["simple", "nounpp"]) & (S_.unit == "expert_position")]
    if "path_grad_rw" in set(two.ranking):
        tw = two[two.ranking.isin(["relp", "rw", "path_grad_rw", "path_relp", "exact", "exact_noL0-2"])]
        tw = tw.groupby(["model", "intervention", "ranking", "budget"]).value.mean().reset_index()
        blocks.append(("Router-aware and multi-step rankings vs RelP and exact (simple + nounpp only, expert-positions; denoise = faithfulness, noise = share left)",
                       tw.pivot_table(index=["model", "intervention", "ranking"], columns="budget", values="value").reset_index(), 2, None))
    if len(D2):
        blocks.append(("D2: RelP list, Phase 8 vs Phase 7 (same pairs, other batch composition)",
                       D2.groupby(["model", "intervention"]).agg(n=("diff", "size"), max_abs_diff=("diff", lambda x: float(np.abs(x).max())),
                                                                 mean_diff=("diff", "mean")).reset_index(), 3, None))
    blocks.append(("Additivity: sum of single exact effects vs the joint patch of the exact ranking's top-K (normalised by the paired difference)", A_, 3, None))
    write_table("addback", "S2.1 Experts added back vs faithfulness and completeness (SVA, held-out pairs)", blocks)


def s22(models, summary):
    """S2.2: how much the frozen quantities differ between the runs, and whether that predicts RelP's reliability."""
    maps, pred, split = [], [], []
    for model in models:
        for task in D.TASKS:
            d = D.task_dir(model, task)
            if not _complete(d / "p8_probe"):
                continue
            z = np.load(d / "p8_probe/probe.npz")
            first = int(z["first_changed"])
            sp = z["split"]
            L, T = z["jaccard"].shape[1], z["jaccard"].shape[2]
            qs = ["jaccard", "tv_w", "dlogit_rms", "dsig_mean", "dsig_frac", "lognorm1", "lognorm2", "attn_tv", "resid_rel"]
            disc = sp == "discovery"
            for l in range(L):
                for t in range(first, T):
                    maps.append({"model": model, "task": task, "layer": l, "pos": t,
                                 **{q: float(np.nanmean(np.abs(z[q][disc, l, t]) if q.startswith("lognorm") else z[q][disc, l, t])) for q in qs}})
            # per-pair features (forward only): means over layers and positions from the changed one on
            feat = {}
            for q in qs:
                x = np.abs(z[q][:, :, first:]) if q.startswith("lognorm") else z[q][:, :, first:]
                feat[q] = np.nanmean(x, axis=(1, 2))
                feat[q + "_late"] = np.nanmean(x[:, L - 8:], axis=(1, 2))
            feat["min_margin"] = np.minimum(z["margin_A"], z["margin_B"])[:, :, first:].mean(axis=(1, 2))
            F = pd.DataFrame(feat)
            F["row_id"], F["split"] = z["row_id"], sp
            pp = pd.read_parquet(OUT / f"pairs_{model}_{task}.parquet")
            rows = [json.loads(l) for l in (ROOT / f"data/relp_sva/{model}_paper_v1/{task}/discovery.jsonl").read_text().splitlines()]
            pp["row_id"] = [rows[i]["row_id"] for i in pp.row]
            J = pp.merge(F, on="row_id")
            for f_ in [c for c in F.columns if c not in ("row_id", "split")]:
                pred.append({"model": model, "task": task, "feature": f_, **{f"spearman_{y}": spearman(J[f_], J[y]) for y in
                                                                             ("pearson", "late_pearson", "rel_l2", "top20_overlap")}})
            # held-out: split validation / test pairs at the discovery median of the chosen predictor
            if _complete(d / "p8_addback"):
                iv = pd.read_parquet(d / "p8_addback/interventions.parquet")
                for f_ in ("jaccard", "tv_w_late", "dsig_mean", "resid_rel"):
                    thr = float(F[F.split == "discovery"][f_].median())
                    ho = F[F.split != "discovery"].set_index("row_id")[f_]
                    hi_rows = set(ho[ho >= thr].index)
                    for side, rs in (("at/above median", hi_rows), ("below median", set(ho.index) - hi_rows)):
                        for rk in ("relp", "exact", "lu", "random"):
                            for K in (5, 20):
                                x = iv[(iv.ranking == rk) & (iv.budget == K) & (iv.intervention == "denoise") & (iv.unit == "expert_position") & iv.row_id.isin(rs)]
                                if len(x) == 0:
                                    continue
                                split.append({"model": model, "task": task, "feature": f_, "side": side, "ranking": rk, "K": K,
                                              "pairs": int(x.row_id.nunique()),
                                              "faithfulness": float((x.margin - x.margin_B).mean() / (x.margin_A - x.margin_B).mean())})
                    # discovery-side agreement in the same split
                    dz = J.set_index("row_id")
                    for side, msk in (("at/above median", dz[f_] >= thr), ("below median", dz[f_] < thr)):
                        split.append({"model": model, "task": task, "feature": f_, "side": side, "ranking": "discovery per-pair agreement",
                                      "K": 0, "pairs": int(msk.sum()), "faithfulness": float(dz[msk].pearson.median())})
    if not maps:
        return
    M, P, S_ = pd.DataFrame(maps), pd.DataFrame(pred), pd.DataFrame(split)
    M.to_parquet(OUT / "s22_maps.parquet", index=False)
    summary["s22"] = {"predictors": P.to_dict(orient="records"), "split": S_.to_dict(orient="records")}
    Mb = M.assign(band=D.band_of(M.layer.values, 48)).copy()
    Mb.loc[Mb.model == "mixtral", "band"] = D.band_of(Mb[Mb.model == "mixtral"].layer.values, 32)
    mt = Mb.groupby(["model", "task", "band"])[["jaccard", "tv_w", "dsig_mean", "lognorm2", "attn_tv", "resid_rel"]].mean().reset_index()
    blocks = [("Clean vs corrupted run, discovery means by layer band (positions from the changed word on)", mt, 3,
               "jaccard = top-k set overlap (1 = same experts); tv_w = total variation of the routing weights; dsig_mean = mean |change| of the SiLU gate sigmoid(g) of experts routed in both runs; lognorm2 = |log| ratio of the MoE-input RMS; attn_tv = total variation of the attention pattern; resid_rel = ||h_A - h_B|| / ||h_B||."),
              ("Spearman of per-pair RelP-vs-exact agreement with forward-only features (discovery)", P, 3, None)]
    if len(S_):
        blocks.append(("Pairs split at the discovery median of a feature: held-out faithfulness of each ranking (denoise) and discovery agreement", S_, 3, None))
    write_table("probe", "S2.2 Gate probe: what differs between the runs, and does it predict where RelP is reliable", blocks)


